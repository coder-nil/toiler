//! 内置供应商表（**写死**）。
//!
//! pi-desktop 的「模型 → 添加模型 → 供应商」面板列的**不是** `models.json` 里的
//! 自定义 provider，而是 pi 的 provider 目录：`@earendil-works/pi-ai` 的
//! `builtinProviders()`（1.4.0 版 42 家）**加上 pi-desktop 自己注册的 2 家**
//! （`apisets` / `qoder-cn`，见本文末的 `DESKTOP_PROVIDERS`），一共 44 家。
//! rpi 是 crates.io 上的 Rust 版，只有三种 `api` 协议的实现（见 `catalog.rs`）、
//! **没有**目录接口，所以这份表只能写死在 toiler 里。
//!
//! ## 数据来源
//!
//! 从 pi-desktop 仓库的 `node_modules/@earendil-works/pi-ai/dist/providers/`
//! 提取（`all.js` 的 `builtinProviders()` + `getBuiltinModels()`）：
//!
//! ```js
//! import('./node_modules/@earendil-works/pi-ai/dist/providers/all.js').then(m => {
//!   const rows = m.builtinProviders().map(p => ({
//!     id: p.id,
//!     name: p.name,
//!     baseUrl: p.baseUrl ?? null,
//!     apiKey: Boolean(p.auth?.apiKey),
//!     oauth: p.auth?.oauth?.name ?? null,
//!     modelIds: m.getBuiltinModels(p.id).map(x => x.id),
//!   }));
//!   console.log(JSON.stringify(rows, null, 1));
//! });
//! ```
//!
//! 升级 `rpi-*` 或 pi-desktop 后重跑这段脚本，把差异同步到本文件。
//!
//! ## 只存面板需要的字段
//!
//! | 字段 | 谁在用 | pi 的等价物 |
//! |---|---|---|
//! | `id` / `name` / `base_url` | 供应商卡片、`/api/auth/*` 的 `id`/`displayName`/`baseUrl` | `Provider.id` / `name` / `baseUrl` |
//! | `api_key` | 是否进「API Key」列表 | `Boolean(provider.auth.apiKey.login)` |
//! | `oauth` | 是否进「订阅（OAuth）」列表、卡片标题 | `provider.auth.oauth.name` |
//! | `models` | 卡片的「N models」（`modelCount`） | `getBuiltinModels(id)`（只取 chat 模型） |
//!
//! `models` **不是**模型目录：toiler 的 `/api/models` 仍然只读 `models.json`
//! （见 `catalog.rs`），这里存 id 列表只为算准 `modelCount`、并在用户自己往
//! `models.json` 里写了同名 provider 时去重。
//!
//! ## 能力边界
//!
//! 表里的 `api` 协议并不都能用：`bedrock-converse-stream`、`google-generative-ai`、
//! `google-vertex`、`azure-openai-responses`、`mistral-conversations`、
//! `openai-codex-responses`、`typesafe-system-one`、`pi-messages`、
//! `openrouter-images` 这几个 rpi 没有实现，`catalog.rs` 会 warn 跳过；
//! 只有 `openai-completions` / `openai-responses` / `anthropic-messages` 是通的。
//! 供应商照样列出来（与 pi 的面板一致），能不能跑取决于 `api`。

/// 一家内置供应商（pi SDK provider 目录的一条）。
#[derive(Debug, Clone, Copy)]
pub struct BuiltinProvider {
    pub id: &'static str,
    pub name: &'static str,
    /// `None` 表示该 provider 必须由用户自己填（bedrock/azure/vertex 这类）。
    pub base_url: Option<&'static str>,
    /// 是否声明了 API Key 登录方式。
    pub api_key: bool,
    /// OAuth 登录方式的名字（`Some` 表示是订阅制/双通道）。
    pub oauth: Option<&'static str>,
    /// pi 目录里的 chat 模型 id。只用于 `modelCount` 与去重，不是模型目录。
    pub models: &'static [&'static str],
}

