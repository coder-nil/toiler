/// 面板上的全部供应商：SDK 目录 42 家 + pi-desktop 自注册 2 家。
pub fn all() -> impl Iterator<Item = &'static BuiltinProvider> {
    PROVIDERS.iter().chain(DESKTOP_PROVIDERS)
}

/// 按 id 查一家；自建 provider 不在这张表里，返回 `None`。
pub fn find(id: &str) -> Option<&'static BuiltinProvider> {
    all().find(|provider| provider.id == id)
}

/// 「订阅」卡片标题：pi 用 `OAUTH_DISPLAY_NAMES[id] ?? oauth.name ?? name`。
pub fn oauth_display_name(provider: &BuiltinProvider) -> String {
    if let Some((_, display)) = OAUTH_DISPLAY_NAMES
        .iter()
        .find(|(id, _)| *id == provider.id)
    {
        return (*display).to_string();
    }
    provider
        .oauth
        .map(str::to_string)
        .unwrap_or_else(|| provider.name.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_matches_the_pi_catalog() {
        assert_eq!(PROVIDERS.len(), 42);
        assert_eq!(DESKTOP_PROVIDERS.len(), 2);
        assert_eq!(all().count(), 44);
        // 双通道（apiKey + OAuth）在 pi 里是 8 家，只有 openai-codex 是纯 OAuth。
        let oauth: Vec<&str> = all()
            .filter(|provider| provider.oauth.is_some())
            .map(|provider| provider.id)
            .collect();
        assert_eq!(
            oauth,
            vec![
                "anthropic",
                "github-copilot",
                "kimi-coding",
                "meta",
                "openai",
                "openai-codex",
                "openrouter",
                "radius",
                "xai",
                "qoder-cn",
            ]
        );
        let codex = find("openai-codex").unwrap();
        assert!(!codex.api_key);
        assert_eq!(oauth_display_name(codex), "ChatGPT Plus/Pro");
        assert_eq!(find("not-a-provider").map(|p| p.id), None);
        // 面板上的「N models」要有真数据，全是空表就说明提取错了。
        let total: usize = PROVIDERS.iter().map(|provider| provider.models.len()).sum();
        assert_eq!(total, 1599);

        // pi-desktop 自注册的两家：订阅区标题直接用 oauth 名，且不在 SDK 目录里。
        let qoder = find("qoder-cn").unwrap();
        assert_eq!(qoder.name, "Qoder CN");
        assert!(!qoder.api_key);
        assert_eq!(oauth_display_name(qoder), "Qoder CN (subscription)");
        assert_eq!(qoder.models.len(), 15);
        let apisets = find("apisets").unwrap();
        assert!(apisets.api_key);
        assert!(apisets.oauth.is_none());
        assert!(PROVIDERS.iter().all(|provider| provider.id != "qoder-cn"));
    }
}
